CREATE TABLE DEPARTMENTS (DEPT_ID INT PRIMARY KEY, DEPT_NAME VARCHAR(50));

CREATE TABLE EMPLOYEES (
	EMP_ID INT PRIMARY KEY,
	EMP_NAME VARCHAR(50),
	DEPT_ID INT,
	SALARY INT,
	FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENTS (DEPT_ID)
);

