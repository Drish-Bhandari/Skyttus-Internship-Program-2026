	-- Display employee name with department name
SELECT
	EMP_NAME AS EMPLOYEE,
	DEPT_NAME AS DEPARTMENT
FROM
	EMPLOYEES E
	JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
	-- Display employees earning more than 50,000 
SELECT
	EMP_NAME AS EMPLOYEE,
	DEPT_NAME AS DEPARTMENT,
	SALARY
FROM
	EMPLOYEES E
	JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
WHERE
	SALARY > 50000
	-- Display department-wise total salary
SELECT
	DEPT_NAME AS DEPARTMENT,
	SUM(SALARY) AS TOTAL_SALARY
FROM
	EMPLOYEES E
	JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
GROUP BY
	D.DEPT_NAME
	-- Display departments with more than 2 employees
SELECT
	DEPT_NAME AS DEPARTMENT,
	COUNT(*) AS TOTAL_EMP
FROM
	DEPARTMENTS D
	JOIN EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID
GROUP BY
	DEPT_NAME
HAVING
	COUNT(*) > 2
	--Display employees without a department
SELECT
	E.EMP_ID,
	E.EMP_NAME,
	D.DEPT_NAME,
	E.SALARY
FROM
	EMPLOYEES E
	LEFT JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
WHERE
	D.DEPT_ID IS NULL;


